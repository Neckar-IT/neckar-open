package it.neckar.projects.common

/**
 * Type-safe wrapper for a worktree offset (0..[WorktreeDevPorts.MaxOffset]).
 * Prevents accidental mix-ups between offsets and product indices, and
 * validates the range at construction time.
 */
@JvmInline
value class WorktreeOffset(val value: Int) {
  init {
    require(value in 0..WorktreeDevPorts.MaxOffset) {
      "WorktreeOffset must be in 0..${WorktreeDevPorts.MaxOffset}, was $value"
    }
  }

  override fun toString(): String = value.toString()
}

/**
 * Systematic port allocation for local development across products and git worktrees.
 *
 * ## Schema
 *
 * Every product gets a 100-port slot starting at [BasePort]:
 *
 * ```
 * Slot start:  BasePort + productIndex × ProductSlotSize   (10000, 10100, 10200, …)
 * Backend:     slot + BackendStart + worktreeOffset           (positions 00..08)
 * UI:          slot + uiStart     + worktreeOffset            (positions 10..18)
 * Admin UI:    slot + AdminUiStart + worktreeOffset          (positions 20..28, if applicable)
 * Secondary:   slot + SecondaryServiceStart + worktreeOffset (positions 30..38, if applicable)
 * Spare:       position 09, 19, 29, 39..99
 * ```
 *
 * Reading a port: given port 10312
 *   - `(10312 - 10000) / 100 = 3` → product index 3 (GitLab-Companion)
 *   - `10312 % 100 = 12` → position 12 → UI (10..18), offset `12 - 10 = 2`
 *
 * ## Product index assignment
 *
 * Each product declares its [ProductIndex] in the `productDeclaration { }` of its declaring project;
 * the plugin derives the ports via [ServiceSlot.port] and [UiSlot.devPort] — no port literals. The dev
 * landing page (`https://localdev`, generated by `LandingPageGenerator`) shows the index badge of every
 * product whose domain has a UI or a service; a product without such a domain and the hand-written
 * Lizergy descriptors hold their index without an entry there.
 *
 * Which indices are taken is not written down here. `verifyProjectDeclarations` fails on an index,
 * a domain or a port two projects declare. Two hand-written descriptors outside this module keep slots 4 and 5;
 * `verifyProjectDeclarations` keeps them from every declaration.
 *
 * ## Shell-side mirror
 *
 * The port derivation functions of the shell scripts must use the
 * same [PortStep] (= 1). They receive the already-computed base port (e.g.
 * 10100 for Patterns backend offset 0) from the product's `dev.sh` script,
 * and add `offset * PortStep` on top.
 *
 * ## Worktree offset
 *
 * Each git worktree is assigned a persistent offset via
 * `git config --worktree dev.portOffset <N>` where `N` is in [range] (0..8).
 */
object WorktreeDevPorts {
  /**
   * First port of the development port range. Chosen to be above all
   * commonly-used service ports (HTTP 8080, Prometheus 9090,
   * Elasticsearch 9200/9300, etcd 2379/2380, …).
   */
  const val BasePort: Int = 10000

  /**
   * Size of the port slot allocated to each product. Within this slot,
   * [BackendStart] and [uiStart] define where each service type begins.
   */
  const val ProductSlotSize: Int = 100

  /**
   * Offset within a product slot where backend ports start.
   * Backend ports occupy positions [BackendStart]..[BackendStart + MaxOffset].
   */
  const val BackendStart: Int = 0

  /**
   * Offset within a product slot where UI (Vite/Astro dev server) ports start.
   * UI ports occupy positions [uiStart]..[uiStart + MaxOffset].
   */
  const val uiStart: Int = 10

  /**
   * Offset within a product slot where a second (admin) UI's ports start.
   * Admin-UI ports occupy positions [AdminUiStart]..[AdminUiStart + MaxOffset].
   */
  const val AdminUiStart: Int = 20

  /**
   * Offset within a product slot where a second backend service's ports start.
   * Its ports occupy positions [SecondaryServiceStart]..[SecondaryServiceStart + MaxOffset].
   */
  const val SecondaryServiceStart: Int = 30

  /**
   * Maximum worktree offset value. Offset 0 is the default slot (plain subdomain),
   * offsets 1..[MaxOffset] are additional slots with suffixed subdomains.
   */
  const val MaxOffset: Int = 8

  /**
   * Port shift per worktree offset step. With [PortStep] = 1, each
   * offset increments the port by exactly 1.
   */
  const val PortStep: Int = 1

  /**
   * Full range of worktree offsets including the default slot 0.
   */
  val range: IntRange = 0..MaxOffset

  /**
   * Range of additional worktree slots (excluding the default slot 0).
   */
  val additionalSlots: IntRange = 1..MaxOffset

  /**
   * Computes the base backend port for a product (at worktree offset 0).
   */
  fun backendPort(productIndex: ProductIndex): Port {
    return Port(BasePort + productIndex.value * ProductSlotSize + BackendStart)
  }

  /**
   * Computes the base UI port for a product (at worktree offset 0).
   */
  fun uiPort(productIndex: ProductIndex): Port {
    return Port(BasePort + productIndex.value * ProductSlotSize + uiStart)
  }

  /**
   * Computes the base admin-UI port for a product (at worktree offset 0).
   * Used by products with a second frontend (e.g. Patterns' admin UI).
   */
  fun adminUiPort(productIndex: ProductIndex): Port {
    return Port(BasePort + productIndex.value * ProductSlotSize + AdminUiStart)
  }

  /**
   * Computes the base port of a product's second backend service (at worktree offset 0).
   */
  fun secondaryServicePort(productIndex: ProductIndex): Port {
    return Port(BasePort + productIndex.value * ProductSlotSize + SecondaryServiceStart)
  }

  /**
   * Returns the worktree-scoped subdomain for a given base subdomain and offset.
   * [WorktreeOffset] 0 yields the base subdomain unchanged; offsets 1..[MaxOffset]
   * append the offset digit (e.g. `patterns` → `patterns3` for offset 3).
   */
  fun subdomainForOffset(base: String, offset: WorktreeOffset): String {
    return if (offset.value == 0) base else "$base${offset.value}"
  }

  /** The local host of [base] at [offset]: `patterns` at offset 3 → `patterns3.localdev`. */
  fun localhostHostForOffset(base: String, offset: WorktreeOffset): Domain {
    return Domain(LocalDev.host(subdomainForOffset(base, offset)))
  }

  /** The local host of [base] in every worktree slot: `patterns.localdev`, `patterns1.localdev` … */
  fun localhostHosts(base: String): List<Domain> {
    return range.map { offset -> localhostHostForOffset(base, WorktreeOffset(offset)) }
  }
}
