package it.neckar.open.charting.api.sanitizing

/**
 * Ensures that this enum value is in fact an enum value.
 *
 * On Kotlin/Wasm this is a no-op: the type system is strict at the interop boundary - a JS string
 * can never reach a `T : Enum<T>` receiver (the export adapter throws a ClassCastException first).
 * The JS actual needs the enumValueOf round-trip because plain strings do arrive as enum values there.
 */
actual inline fun <reified T : Enum<T>> T.sanitize(): T {
  return this
}
