import { readFileSync, readdirSync } from "node:fs";
import { basename, dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const packageDir = dirname(dirname(fileURLToPath(import.meta.url)));
const generatedDirs = ["src/components", "src/hooks", "src/lib"];
// The marker names the path in neckar-hub, which also holds in the export of internal/open, where the directory depth differs.
const scriptPath = "internal/open/commons/typescript/typescript-react-ui-primitives/scripts/update-primitives.sh";

const { style } = JSON.parse(readFileSync(join(packageDir, "components.json"), "utf8")) as { style: string };

/** Package-relative paths of every `.ts`/`.tsx` file the shadcn CLI writes. */
function generatedFiles(): string[] {
  return generatedDirs.flatMap((dir) => {
    let entries: string[];
    try {
      entries = readdirSync(join(packageDir, dir), { recursive: true, encoding: "utf8" });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") {
        return [];
      }
      throw error;
    }
    return entries.filter((entry) => [".ts", ".tsx"].includes(extname(entry))).map((entry) => join(dir, entry));
  });
}

/** The marker `scripts/update-primitives.sh` writes into the first lines of the file, blank line included. */
function expectedMarker(file: string): string {
  const item = basename(file, extname(file));
  return [
    "// GENERATED by shadcn CLI — do not edit by hand.",
    `// Source: https://ui.shadcn.com/r/styles/${style}/${item}.json`,
    `// Run ${scriptPath}; a customization belongs in a wrapper under internal/open/commons/typescript/typescript-react-ui/src/components/primitives/<name>/.`,
    "",
  ].join("\n");
}

describe("shadcn CLI output", () => {
  it("finds the CLI files", () => {
    expect(generatedFiles()).not.toHaveLength(0);
  });

  it.each(generatedFiles())("%s starts with the generated marker", (file) => {
    const firstLines = readFileSync(join(packageDir, file), "utf8").split("\n").slice(0, 4).join("\n");
    expect(firstLines, `${file}: missing or stale generated marker; run ${scriptPath}`).toBe(expectedMarker(file));
  });
});
