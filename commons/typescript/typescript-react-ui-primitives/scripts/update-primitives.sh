#!/usr/bin/env bash
#
# update-primitives.sh - Rewrites every installed shadcn primitive with the current registry state.
#
# Steps:
#   1. reads the installed components from `shadcn info --json` and appends the names it received
#   2. runs `shadcn add <components> style --yes --overwrite`; the style item, which `shadcn info` does not
#      list, writes src/shadcn-theme.css and src/lib/utils.ts
#   3. fails when pnpm added or changed a catalog entry during the CLI run
#   4. sets every dependency with a version back to `catalog:`; after such a change it reinstalls
#      the workspace, so pnpm-lock.yaml follows the catalog versions
#   5. writes the ADL 0180 marker into the first lines of every `.ts`/`.tsx` file below
#      `src/components/`, `src/hooks/` and `src/lib/`, replacing a marker the file already carries
#   6. formats `src/` with oxfmt
#
# The CLI runs with `pnpm_config_catalog_mode=prefer`: `chart` asks for a recharts version that
# differs from the catalog, and `catalogMode: strict` aborts the CLI before it writes a file.
# `prefer` also adds a dependency the catalog lacks to the catalog, with a `^` range.
#
# Usage:
#   update-primitives.sh [<name>...]
#
#   <name>  a registry item to add, e.g. `separator`; the installed components are rewritten as well
#
# Exit status: 1 when `shadcn info` lists no component, a dependency is missing from the catalog in
# pnpm-workspace.yaml, or the CLI run changed the catalog; otherwise the failing command's exit code.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACKAGE_DIR="$(dirname "$SCRIPT_DIR")"
PACKAGE_JSON="$PACKAGE_DIR/package.json"
COMPONENTS_JSON="$PACKAGE_DIR/components.json"

log_info() {
  printf 'INFO: %s\n' "$*" >&2
}

die() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

# The directory of the pnpm workspace this package belongs to, wherever that workspace is checked out.
workspace_root() {
  local directory="$PACKAGE_DIR"
  until [[ -f "$directory/pnpm-workspace.yaml" ]]; do
    [[ "$directory" != "/" ]] || die "$PACKAGE_DIR: no pnpm-workspace.yaml in any parent directory"
    directory="$(dirname "$directory")"
  done
  printf '%s\n' "$directory"
}

WORKSPACE_ROOT="$(workspace_root)"
WORKSPACE_FILE="$WORKSPACE_ROOT/pnpm-workspace.yaml"

command -v jq >/dev/null || die "jq is not installed"
command -v pnpm >/dev/null || die "pnpm is not installed"

# Prints "<name> <spec>" for every entry of the default catalog in pnpm-workspace.yaml, quotes removed.
catalog_entries() {
  awk '
    /^catalog:/ { in_catalog = 1; next }
    in_catalog && /^[^ #]/ { exit }
    in_catalog && match($0, /^  [^ :#]+:/) {
      name = substr($0, 3, RLENGTH - 3)
      spec = substr($0, RLENGTH + 1)
      sub(/[ \t]+#.*/, "", spec)
      gsub(/^[ \t]+|[ \t]+$/, "", spec)
      gsub(/^["'"'"']|["'"'"']$/, "", spec)
      gsub(/["'"'"']/, "", name)
      print name, spec
    }
  ' "$WORKSPACE_FILE"
}

# Succeeds when the catalog as it stood before the CLI run holds the name. A here-string instead of a
# pipe: `grep -q` closing early makes the writer die of SIGPIPE, which pipefail reports as a miss.
catalog_had() {
  grep -qxF "$1" <<<"$catalog_names_before"
}

# Prints "<section> <name> <spec>" for every dependency whose spec is neither `catalog:` nor `workspace:`.
dependencies_outside_catalog() {
  jq -r '
    ["dependencies", "devDependencies", "peerDependencies"][] as $section
    | .[$section] // {} | to_entries[]
    | select(.value | test("^(catalog|workspace):") | not)
    | "\($section) \(.key) \(.value)"
  ' "$PACKAGE_JSON"
}

# Prints the ADL 0180 marker of the file named by $1: three comment lines and a blank line; the registry
# item is its basename. oxfmt's import sort moves a comment that touches the first import along with it.
generated_marker() {
  local item
  item="$(basename "$1")"
  item="${item%.*}"
  printf '%s\n' \
    "// GENERATED by shadcn CLI — do not edit by hand." \
    "// Source: https://ui.shadcn.com/r/styles/$style/$item.json" \
    "// Run $script_path; a customization belongs in a wrapper under internal/open/commons/typescript/typescript-react-ui/src/components/primitives/<name>/." \
    ""
}

# Writes the marker into the first lines of the file named by $1. A marker the file already carries
# (a file the CLI left untouched) is replaced, so a second run writes the same bytes.
write_marker() {
  local file="$1"
  {
    generated_marker "$file"
    if [[ "$(head -n 1 "$file")" == "// GENERATED by shadcn CLI"* ]]; then
      tail -n +4 "$file" | sed '1{/^$/d}'
    else
      cat "$file"
    fi
  } >"$file.tmp"
  mv "$file.tmp" "$file"
}

# Read before the CLI run, so a components.json without a style fails before any file changes.
style="$(jq -er '.style' "$COMPONENTS_JSON")"
script_path="${SCRIPT_DIR#"$WORKSPACE_ROOT"/}/update-primitives.sh"

components_json="$(pnpm --silent --dir "$PACKAGE_DIR" exec shadcn info --json)"
# A command substitution keeps a jq failure (no `components` array) from reading as an empty list.
component_lines="$(jq -r '.components[]' <<<"$components_json")"
if [[ -z "$component_lines" ]]; then
  die "shadcn info reports no components"
fi
mapfile -t components < <(printf '%s\n' "$component_lines" "$@" | awk '!seen[$0]++')
log_info "Updating ${#components[@]} components: ${components[*]}"

catalog_before="$(catalog_entries)"
catalog_names_before="$(cut -d " " -f 1 <<<"$catalog_before")"

# `exec` passes the exit code of the CLI through, `run` turns every failure into 1.
pnpm_config_catalog_mode=prefer pnpm --dir "$PACKAGE_DIR" exec shadcn add "${components[@]}" style --yes --overwrite

catalog_after="$(catalog_entries)"
while read -r name spec; do
  [[ -n "$name" ]] || continue
  if ! catalog_had "$name"; then
    die "$name $spec: missing from the catalog in pnpm-workspace.yaml, pnpm added it during the CLI run"
  fi
  if ! grep -qxF "$name $spec" <<<"$catalog_before"; then
    die "$name $spec: pnpm changed the catalog entry in pnpm-workspace.yaml during the CLI run"
  fi
done <<<"$catalog_after"

outside_lines="$(dependencies_outside_catalog)"
restored=0
while read -r section name spec; do
  [[ -n "$name" ]] || continue
  if ! catalog_had "$name"; then
    die "$name $spec: missing from the catalog in pnpm-workspace.yaml"
  fi
  jq --indent 2 --arg section "$section" --arg name "$name" '.[$section][$name] = "catalog:"' "$PACKAGE_JSON" >"$PACKAGE_JSON.tmp"
  mv "$PACKAGE_JSON.tmp" "$PACKAGE_JSON"
  log_info "$section $name: $spec -> catalog:"
  restored=$((restored + 1))
done <<<"$outside_lines"

# The CLI's `pnpm add` resolved the lockfile to its own versions; the install resolves the catalog versions.
if [[ $restored -gt 0 ]]; then
  pnpm --dir "$WORKSPACE_ROOT" install --no-frozen-lockfile
fi

marker_dirs=()
for dir in components hooks lib; do
  if [[ -d "$PACKAGE_DIR/src/$dir" ]]; then
    marker_dirs+=("$PACKAGE_DIR/src/$dir")
  fi
done
marked=0
if [[ ${#marker_dirs[@]} -gt 0 ]]; then
  while IFS= read -r -d '' file; do
    write_marker "$file"
    marked=$((marked + 1))
  done < <(find "${marker_dirs[@]}" -type f \( -name '*.ts' -o -name '*.tsx' \) -print0)
fi
log_info "Marked $marked files as generated"

pnpm --dir "$PACKAGE_DIR" exec oxfmt --write src
