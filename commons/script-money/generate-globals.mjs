// Writes dist/src/script-money-globals.d.ts from the declarations tsc emitted for src/scriptMoney.ts. Without `export`
// the file is a global script, so a pricing script reaches every function without an import, as in the sandbox.
import { readFileSync, writeFileSync } from "node:fs";

const emitted = readFileSync(new URL("./dist/src/scriptMoney.d.ts", import.meta.url), "utf8");
const globals = emitted.replace(/^export declare /gm, "declare ");

if (/^\s*(export|import)\b/m.test(globals)) {
  throw new Error("dist/src/scriptMoney.d.ts holds an import or export besides `export declare`; the globals file would become a module");
}

const header = [
  "// GENERATED by generate-globals.mjs of @neckar-hub/script-money — do not edit by hand.",
  "// Source: src/scriptMoney.ts",
  "",
].join("\n");

writeFileSync(new URL("./dist/src/script-money-globals.d.ts", import.meta.url), header + globals);
