package it.neckar.ksp.spec.harvest

import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import it.neckar.ksp.EmptySymbolProcessor
import it.neckar.ksp.isRunningForJvmPlatform
import it.neckar.ksp.spec.harvest.model.HarvestedClassSpec

/**
 * Provides instances of [SpecHarvestProcessor].
 *
 * ## Incremental Compilation Behavior
 *
 * This processor is designed to work correctly with incremental compilation:
 *
 * 1. **Individual JSON files**: Each `@Serializable` class generates its own JSON file
 *    in `harvested-specs/`. These files are tracked by KSP's dependency system.
 *
 * 2. **Aggregation via Gradle**: The [MergeSpecHarvestResultTask] collects all individual
 *    JSON files and merges them into a single [SpecHarvestResult] file.
 *
 * 3. **Context limitation**: The [Context.result] only contains specs processed in the
 *    *current* KSP run. During incremental builds, this will only include changed classes.
 *    For the complete set of all specs, use the merged result file instead.
 */
class SpecHarvestProcessorProvider : SymbolProcessorProvider {
  val context: Context = Context()

  override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor {
    environment.logger.logging("Creating ${SpecHarvestProcessor::class.simpleName} for ${environment.platforms}")

    if (environment.platforms.size != 1) {
      error("Only one platform is supported but was ${environment.platforms}")
    }

    if (environment.isRunningForJvmPlatform().not()) {
      //Only JVM is supported
      return EmptySymbolProcessor
    }

    return SpecHarvestProcessor(
      codeGenerator = environment.codeGenerator,
      logger = environment.logger,
      options = environment.options,
      context = context,
    )
  }

  /**
   * Holds the results collected during a single KSP processing run.
   *
   * ## Important: Incremental Compilation
   *
   * During incremental builds, [result] only contains specs for classes that were
   * (re-)processed in this specific KSP run - NOT all `@Serializable` classes in the project.
   *
   * This context is primarily useful for:
   * - **Testing**: Verifying processor behavior in unit tests (which always run from clean state)
   * - **Single-run scenarios**: When a full (non-incremental) build is guaranteed
   *
   * For production use cases that need ALL harvested specs, use the merged result file
   * generated by the Gradle [MergeSpecHarvestResultTask] instead.
   */
  class Context {
    /**
     * The specs collected during this KSP processing run.
     *
     * **Warning**: During incremental builds, this list is incomplete.
     * Only contains specs for classes processed in the current run.
     *
     * @see SpecHarvestProcessorProvider for details on incremental compilation behavior
     */
    val result: MutableList<HarvestedClassSpec> = mutableListOf()
  }
}

