package it.neckar.ksp.ts.model

import assertk.*
import it.neckar.ksp.ts.writeImports
import it.neckar.ksp.ts.writeTypescriptDefinitionForElementsWithNamespace
import it.neckar.open.test.utils.isEqualIgnoringWhitespacesEmptyLines
import org.junit.jupiter.api.Test
import java.io.StringWriter

/**
 *
 */
class TsNestedClassTest {
  @Test
  fun `test code generation for nested class`() {
    val nestedClass = TsClass(
      name = "NestedClass",
      namespace = TsNamespace(name = "ParentClass"),
      doc = "This is a nested class",
      kotlinSource = "it.neckar.NestedClass",
      constructors = emptyList(),
      superTypes = emptyList(),
      functions = emptyList(),
      properties = emptyList(),
      typeParameters = emptyList(),
      companionObject = null,
      )

    //The namespace is generated by it.neckar.ksp.ts.TypeScriptDefinitionGenerationProcessor.writeTypescriptDefinitionForNestedClass

    assertThat(nestedClass.toTypescriptString().trim()).isEqualIgnoringWhitespacesEmptyLines(
      //language=TypeScript
      """
        /**
         * This is a nested class
         */
        export declare class NestedClass {
        }
      """.trimIndent()
    )

    val writer = StringWriter()
    writer.writeTypescriptDefinitionForElementsWithNamespace(listOf(nestedClass))

    assertThat(writer.toString()).isEqualIgnoringWhitespacesEmptyLines(
      //language=TypeScript
      """
        export declare namespace ParentClass {

          /**
           * This is a nested class
           */
          export declare class NestedClass {
          }

        }
      """.trimIndent()
    )
  }

  @Test
  fun testWriteImports() {
    val types = listOf(
      TsType("MyType", namespace = TsNamespace("ParentClass"), classKind = TsType.ClassKind.Class, importedFrom = TsModuleReference.ModuleReference("the-module")),
      TsType("MyType2", namespace = TsNamespace("ParentClass"), classKind = TsType.ClassKind.Class, importedFrom = TsModuleReference.ModuleReference("the-module")),

      TsType("MyType3", namespace = TsNamespace("ParentClass2"), classKind = TsType.ClassKind.Class, importedFrom = TsModuleReference.ModuleReference("the-module")),
      TsType("MyType4", namespace = TsNamespace("ParentClass2"), classKind = TsType.ClassKind.Class, importedFrom = TsModuleReference.ModuleReference("the-module")),

      TsType("MyType5", namespace = null, classKind = TsType.ClassKind.Class, importedFrom = TsModuleReference.ModuleReference("the-module")),
      TsType("MyType6", namespace = null, classKind = TsType.ClassKind.Class, importedFrom = TsModuleReference.ModuleReference("the-module")),
    )

    val writer = StringWriter()
    writer.writeImports(types)
    assertThat(writer.toString()).isEqualIgnoringWhitespacesEmptyLines(
      //language=TypeScript
      """
        import { ParentClass, ParentClass2 } from "./the-module";
        import { MyType5, MyType6 } from "./the-module";
      """.trimIndent()
    )
  }
}
